test('收藏历史只显示当前范围，旧详情不能播放或下载移出的文件，记录保留并可恢复', async ({ page }) => {
  await installCinema(page, '/测试影视/原生示例', '电影')
  const frame = frameOf(page)
  const original = '/测试影视/原生示例/流光.webm', moved = '/空目录/流光.webm'
  const ids = await frame.locator('body').evaluate(async () => {
    const drive = (window as any).tgdrive
    const inside = await drive.files.stat({ path: '/测试影视/原生示例/流光.webm' })
    const outside = await drive.files.stat({ path: '/测试影视/星际旅程 S01E01.mp4' })
    for (const file of [inside, outside]) {
      await drive.storage.set(`favorite:${file.id}`, { file }, null)
      await drive.storage.set(`progress:${file.id}`, { file, seconds: 1, duration: 20, completed: false }, null)
    }
    return { inside: inside.id, outside: outside.id }
  })
  const audit = cinemaRequests(page)
  await frame.locator('.sidebar [data-nav="history"]').click()
  await expect(frame.locator('#items .poster-card')).toHaveCount(1)
  await expect(frame.getByRole('button', { name: '查看影视：流光.webm', exact: true })).toBeVisible()
  await frame.locator('.sidebar [data-nav="favorites"]').click()
  await expect(frame.locator('#items .poster-card')).toHaveCount(1)
  expect(audit.enumerations()).toEqual([])
  const thumbnails = () => audit.calls.filter(call => call.method === 'media.url' && call.params.kind === 'thumbnail' && call.params.id === ids.inside).length
  const before = thumbnails()
  await frame.getByRole('button', { name: '查看影视：流光.webm', exact: true }).click()
  await expect(frame.locator('#detail-favorite')).toBeEnabled()
  // 详情海报先查封面库再申请缩略图票据；等它在移出范围前完成，避免迟到的请求落进下面的审计窗口。
  await expect.poll(thumbnails).toBe(before + 1)
  await rename(page, original, moved)
  try {
    audit.calls.length = 0
    await frame.locator('#detail-download').click()
    await expect(frame.locator('#toast')).toContainText('范围内')
    await frame.locator('#detail-play').click()
    await expect(frame.locator('#play-message')).toContainText('范围内')
    await frame.locator('#player-download').click()
    await expect(frame.locator('#toast')).toContainText('范围内')
    expect(audit.calls.filter(call => call.method === 'media.url' && (call.params.id === ids.inside || call.params.path === moved))).toEqual([])
    await frame.locator('#player-back').click()
    await expect(frame.locator('#items .poster-card')).toHaveCount(0)
    const retained = await frame.locator('body').evaluate(async (_node, { inside, outside }) => {
      const drive = (window as any).tgdrive
      return Promise.all([inside, outside].flatMap(id => [drive.storage.get(`favorite:${id}`), drive.storage.get(`progress:${id}`)]))
    }, ids)
    expect(retained.every(Boolean)).toBe(true)
    await frame.locator('.sidebar [data-nav="library"]').click()
    await createCinemaLibrary(page, '临时片库', '/空目录')
    await frame.locator('.sidebar [data-nav="history"]').click()
    await expect(frame.locator('#items .poster-card')).toHaveCount(1)
    await expect(frame.getByRole('button', { name: '查看影视：流光.webm', exact: true })).toBeVisible()
    await frame.locator('.sidebar [data-nav="library"]').click()
    await frame.getByRole('button', { name: '删除媒体库：临时片库', exact: true }).click()
    await expect(frame.locator('#confirm-text')).toContainText('不删除原文件')
    await frame.locator('#confirm-ok').click()
    await expect(frame.getByRole('button', { name: '进入媒体库：临时片库', exact: true })).toHaveCount(0)
    await frame.locator('.sidebar [data-nav="history"]').click()
    await expect(frame.locator('#items .poster-card')).toHaveCount(0)
  } finally { await rename(page, moved, original) }
})

test('根目录按节点 ID 跟随移动，删除后不误绑定同路径新目录，可编辑重新绑定', async ({ page }) => {
  await installCinema(page, null)
  const frame = frameOf(page), oldPath = '/媒体库目录测试', newPath = '/媒体库目录测试改名'
  expect((await page.request.post('/api/fs/mkdir', { data: { path: oldPath } })).ok()).toBe(true)
  try {
    await createCinemaLibrary(page, '空片库', oldPath)
    const originalId = (await readConfig(page)).libraries[0].directoryId
    await rename(page, oldPath, newPath)
    expect((await page.request.post('/api/fs/mkdir', { data: { path: oldPath } })).ok()).toBe(true)
    await frame.getByRole('button', { name: '进入媒体库：空片库', exact: true }).click()
    await expect(frame.locator('#source-label')).toHaveText(newPath)
    await expect(frame.locator('#empty-title')).toHaveText('此媒体库还没有视频')
    const deleted = await page.request.post('/api/fs/delete', { data: { paths: [newPath], permanent: true } })
    expect((await deleted.json()).deleted).toBe(1)
    const audit = cinemaRequests(page)
    await frame.locator('#refresh').click()
    await expect(frame.locator('#list-status')).toContainText('文件夹不可用')
    expect(audit.enumerations()).toEqual([])
    await frame.locator('#library-edit-current').click()
    await expect(frame.locator('#library-name')).toBeEnabled()
    await frame.locator('#library-name').fill('重新绑定')
    await chooseCinemaDirectory(page, oldPath)
    await frame.locator('#library-save').click()
    await expect(frame.getByRole('button', { name: '进入媒体库：重新绑定', exact: true })).toBeVisible()
    expect((await readConfig(page)).libraries[0].directoryId).not.toBe(originalId)
    await frame.getByRole('button', { name: '删除媒体库：重新绑定', exact: true }).click()
    await frame.locator('#confirm-ok').click()
    await expect(frame.getByRole('button', { name: '进入媒体库：重新绑定', exact: true })).toHaveCount(0)
    await expect(frame.locator('#empty')).toBeVisible()
    expect((await (await page.request.get('/api/fs/list', { params: { path: oldPath } })).json()).path).toBe(oldPath)
    await expect.poll(async () => (await readConfig(page)).libraries).toEqual([])
  } finally {
    await page.request.post('/api/fs/delete', { data: { paths: [oldPath, newPath], permanent: true } })
  }
})

