test('切换媒体库取消旧查询，迟到响应不覆盖新库；配置读取失败不回退全盘', async ({ page }) => {
  await installCinema(page, null)
  const frame = frameOf(page)
  await createCinemaLibrary(page, '电影', '/测试影视')
  await createCinemaLibrary(page, '电视剧', '/测试视频')
  let release!: () => void, intercepted = false
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/apps/cinema/rpc', async route => {
    const body = route.request().postDataJSON()
    if (!intercepted && body.method === 'files.searchPage' && body.params.under === '/测试影视') {
      intercepted = true
      const response = await route.fetch()
      await gate
      await route.fulfill({ response }).catch(() => {})
    } else await route.continue()
  })
  try {
    await frame.getByRole('button', { name: '进入媒体库：电影', exact: true }).click()
    await expect.poll(() => intercepted).toBe(true)
    await frame.locator('.sidebar [data-nav="library"]').click()
    await enterCinemaLibrary(page, '电视剧')
    release()
    await expect(frame.locator('#page-title')).toHaveText('电视剧')
    await expect(frame.getByRole('button', { name: '查看影视：片段 A.webm', exact: true })).toBeVisible()
    await expect(frame.getByRole('button', { name: '查看影视：星际旅程 S01E01.mp4', exact: true })).toHaveCount(0)
  } finally { release(); await page.unroute('**/api/apps/cinema/rpc') }
  const audit = cinemaRequests(page)
  await page.route('**/api/apps/cinema/rpc', async route => {
    const body = route.request().postDataJSON()
    if (body.method === 'storage.get' && body.params.key === 'media-libraries') await route.fulfill({ status: 500, json: { error: '媒体库配置读取失败' } })
    else await route.continue()
  })
  await page.reload()
  await expect(frame.locator('#list-status')).toContainText('媒体库配置读取失败')
  await expect(frame.locator('#items .poster-card')).toHaveCount(0)
  expect(audit.enumerations()).toEqual([])
  await frame.locator('#new-library').click()
  await expect(frame.locator('#library-edit-status')).toContainText('媒体库配置读取失败')
  await expect(frame.locator('#library-save')).toBeDisabled()
})

test('从旧单目录设置升级不自动建库或扫描，旧观看记录保留且可重新纳入', async ({ page }) => {
  await installCinema(page, null)
  await page.goto('/apps')
  expect((await page.request.delete('/api/apps/cinema?purge_data=true')).ok()).toBe(true)
  // 合成旧清单和无扫描页面，只验证真实升级与数据兼容，不依赖旧构建产物。
  const oldPackage = await legacyCinemaPackage()
  const inspection = await page.request.post('/api/apps/inspect', { data: oldPackage, headers: { 'Content-Type': 'application/octet-stream' } })
  expect(inspection.ok()).toBe(true)
  const { digest } = await inspection.json()
  const installed = await page.request.post(`/api/apps/install?digest=${digest}`, { data: oldPackage, headers: { 'Content-Type': 'application/octet-stream' } })
  expect(installed.ok()).toBe(true)
  const old = await installed.json()
  expect((await page.request.patch('/api/apps/cinema/settings', { data: { source_dir: '/测试影视' } })).ok()).toBe(true)
  await page.goto('/apps/cinema')
  const frame = frameOf(page)
  await expect(frame.locator('body')).toHaveText('旧版影视升级夹具')
  const id = await frame.locator('body').evaluate(async () => {
    const drive = (window as any).tgdrive; await drive.ready
    const file = await drive.files.stat({ path: '/测试影视/星际旅程 S01E01.mp4' })
    await drive.storage.set(`favorite:${file.id}`, { file }, null)
    await drive.storage.set(`progress:${file.id}`, { file, seconds: 5, duration: 20, completed: false }, null)
    return file.id
  })
  await page.goto('/apps')
  const index = await (await page.request.get('/api/apps')).json()
  const available = index.available.find((item: any) => item.manifest.id === 'cinema')
  expect((await page.request.post('/api/apps/catalog/cinema/install', { data: { digest: available.digest, expected_revision: old.revision } })).ok()).toBe(true)
  const audit = cinemaRequests(page)
  await page.goto('/apps/cinema')
  await expect(frame.locator('#empty-title')).toHaveText('尚未创建媒体库')
  await expect(frame.locator('#empty')).toBeVisible()
  expect(audit.enumerations()).toEqual([])
  expect(await (await page.request.get('/api/apps/cinema/settings')).json()).toEqual({})
  await frame.locator('.sidebar [data-nav="history"]').click()
  await expect(frame.locator('#empty-title')).toHaveText('暂无媒体库内的记录')
  expect(await frame.locator('body').evaluate(async (_node, id) => !!await (window as any).tgdrive.storage.get(`progress:${id}`), id)).toBe(true)
  await frame.locator('.sidebar [data-nav="library"]').click()
  await createCinemaLibrary(page, '电影', '/测试影视')
  await frame.locator('.sidebar [data-nav="favorites"]').click()
  await expect(frame.locator('#items .poster-card')).toHaveCount(1)
  await expect(frame.getByRole('button', { name: '查看影视：星际旅程 S01E01.mp4', exact: true })).toBeVisible()
})

