const frameOf = (page: Page) => page.frameLocator('iframe')
const readConfig = (page: Page) => frameOf(page).locator('body').evaluate(async () => (await (window as any).tgdrive.storage.get('media-libraries'))?.value)
async function rename(page: Page, from: string, to: string) {
  expect((await page.request.post('/api/fs/rename', { data: { from, to } })).ok()).toBe(true)
}
