import { expect, test } from '@playwright/test'
import { enterCinemaLibrary, installCinema as install } from './cinema-helpers'

test('影视库内首页、详情、收藏和字幕续播，不在点击播放前读取原视频', async ({ page }, info) => {
  const errors: string[] = [], outside: string[] = [], previewReads: number[] = []
  page.on('pageerror', e => errors.push(e.message))
  // 从打开影院前开始计数，不能漏掉首页首屏可能发出的原视频请求。
  page.on('request', request => {
    if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:4187')) outside.push(request.url())
    const match = /\/api\/apps\/media\/([^/?]+)/.exec(request.url())
    if (!match) return
    const claim = JSON.parse(Buffer.from(match[1]!.split('.')[0]!, 'base64url').toString())
    if (claim.purpose === 'preview') previewReads.push(claim.node_id)
  })
  await install(page)
  const frame = page.frameLocator('iframe')
  const videoIds: number[] = await frame.locator('body').evaluate(async () => {
    const drive = (window as any).tgdrive
    return (await drive.files.searchPage({ under: '/测试影视', extensions: ['mp4', 'mkv', 'avi', 'webm'] })).results.map((file: any) => file.id)
  })
  await frame.getByRole('button', { name: '查看影视：星际旅程 S01E01.mp4', exact: true }).click()
  await expect(frame.locator('#episode-count')).toContainText('3 个视频')
  expect(previewReads.filter(id => videoIds.includes(id))).toHaveLength(0)
  await frame.locator('#detail-favorite').click()
  await expect(frame.locator('#detail-favorite')).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: info.outputPath('cinema-desktop-detail.png'), fullPage: true })
  await frame.locator('#detail-play').click()
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime), { timeout: 25000 }).toBeGreaterThan(1)
  await frame.locator('#options-toggle').click()
  await expect(frame.locator('#subtitle option')).toHaveCount(2)
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).textTracks[0]?.cues?.length ?? 0)).toBe(2)
  await frame.locator('#subtitle').selectOption('')
  await frame.locator('#options-close').click()
  await frame.locator('#forward').click()
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime)).toBeGreaterThan(10)
  await frame.locator('#player-back').click()
  await expect(frame.locator('#continue-section')).toBeVisible()
  await page.reload()
  await enterCinemaLibrary(page)
  await frame.getByRole('button', { name: '继续观看：星际旅程 S01E01.mp4', exact: true }).click()
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime)).toBeGreaterThan(10)
  await frame.locator('#options-toggle').click()
  await expect(frame.locator('#subtitle')).toHaveValue('')
  await frame.locator('#player-back').click()
  await frame.locator('.sidebar [data-nav="favorites"]').click()
  await expect(frame.locator('#items .poster-card')).toHaveCount(1)
  expect(errors).toEqual([]); expect(outside).toEqual([])
})

test('真实 MKV 经客户端转封装播放、音轨切换、内嵌字幕和拖动', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await install(page)
  const frame = page.frameLocator('iframe')
  await frame.getByRole('button', { name: '查看影视：星际旅程 S01E02.mkv', exact: true }).click()
  await frame.locator('#detail-play').click()
  await expect(frame.locator('#play-mode')).toContainText('客户端转封装', { timeout: 25000 })
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime), { timeout: 30000 }).toBeGreaterThan(1)
  await expect(frame.locator('#video')).toHaveAttribute('src', /^blob:/)
  await frame.locator('#options-toggle').click()
  await expect(frame.locator('#audio option')).toHaveCount(2)
  await frame.locator('#subtitle').selectOption('embedded:4')
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).textTracks[0]?.cues?.length ?? 0)).toBeGreaterThan(0)
  await frame.locator('#audio').selectOption({ index: 1 })
  await frame.locator('#options-close').click()
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime), { timeout: 30000 }).toBeGreaterThan(2)
  await frame.locator('#forward').click()
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime), { timeout: 30000 }).toBeGreaterThan(11)
  await frame.locator('#rewind').click()
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime), { timeout: 30000 }).toBeLessThan(8)
  await frame.locator('#player-back').click()
  await expect(frame.locator('#video')).not.toHaveAttribute('src', /.+/)
  expect(errors).toEqual([])
})

