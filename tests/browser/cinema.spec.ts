test('暂停后的 MKV 拖动及切换音轨保持暂停，并保存位置和音轨', async ({ page }) => {
  await install(page)
  const frame = page.frameLocator('iframe')
  await frame.getByRole('button', { name: '查看影视：星际旅程 S01E02.mkv', exact: true }).click()
  await frame.locator('#detail-play').click()
  const playback = () => frame.locator('#video').evaluate(v => ({ time: (v as HTMLVideoElement).currentTime, paused: (v as HTMLVideoElement).paused, seeking: (v as HTMLVideoElement).seeking }))
  await expect.poll(async () => (await playback()).time).toBeGreaterThan(1)
  await frame.locator('#toggle-play').click()
  await expect.poll(async () => (await playback()).paused).toBe(true)
  await frame.locator('#forward').click()
  await expect.poll(async () => (await playback()).time).toBeGreaterThan(10)
  await expect.poll(async () => (await playback()).seeking).toBe(false)
  expect((await playback()).paused).toBe(true)
  await frame.locator('#options-toggle').click()
  await frame.locator('#audio').selectOption({ index: 1 })
  await expect.poll(async () => (await playback()).time).toBeGreaterThan(10)
  await expect.poll(async () => (await playback()).seeking).toBe(false)
  expect((await playback()).paused).toBe(true)
  const audio = await frame.locator('#audio').inputValue()
  await frame.locator('#player-back').click()
  await frame.getByRole('button', { name: '继续观看：星际旅程 S01E02.mkv', exact: true }).click()
  await expect.poll(async () => (await playback()).time).toBeGreaterThan(10)
  await frame.locator('#options-toggle').click()
  await expect(frame.locator('#audio')).toHaveValue(audio)
})

test('详情未整理完就播放，仍能恢复同目录选集和下一集', async ({ page }) => {
  await install(page)
  const frame = page.frameLocator('iframe')
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  let intercepted = false
  await page.route('**/api/apps/cinema/rpc', async route => {
    const body = route.request().postDataJSON()
    if (!intercepted && body.method === 'storage.get' && body.params.key.startsWith('favorite:')) {
      intercepted = true
      await gate
    }
    await route.continue().catch(() => {})
  })
  try {
    await frame.getByRole('button', { name: '查看影视：星际旅程 S01E01.mp4', exact: true }).click()
    await expect.poll(() => intercepted).toBe(true)
    await expect(frame.locator('#detail-status')).toHaveText('正在整理同目录合集…')
    await frame.locator('#detail-play').click()
    await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime)).toBeGreaterThan(.2)
    await expect(frame.locator('#next-episode')).toBeEnabled()
    await frame.locator('#next-episode').click()
    await expect(frame.locator('#playing-title')).toContainText('S01E02')
    await expect(frame.locator('#play-mode')).toContainText('客户端转封装')
  } finally { release() }
})

test('播放器键盘焦点不落到背后的片库，退出后恢复导航', async ({ page }) => {
  await install(page, '/测试影视/原生示例')
  const frame = page.frameLocator('iframe')
  await frame.getByRole('button', { name: '查看影视：流光.webm', exact: true }).click()
  await frame.locator('#detail-play').click()
  await expect.poll(() => frame.locator('#video').evaluate(v => (v as HTMLVideoElement).currentTime)).toBeGreaterThan(.2)
  await expect(frame.getByRole('dialog', { name: '影视播放器' })).toBeVisible()
  expect(await frame.locator('#main').evaluate(node => (node as HTMLElement).inert)).toBe(true)
  await frame.locator('#player-back').focus()
  await page.keyboard.press('Shift+Tab')
  await expect(frame.locator('#fullscreen')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(frame.locator('#player-back')).toBeFocused()
  await frame.locator('#options-toggle').click()
  await page.keyboard.press('Escape')
  await expect(frame.locator('#play-options')).not.toBeVisible()
  await expect(frame.locator('#options-toggle')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(frame.locator('#player')).not.toBeVisible()
  expect(await frame.locator('#main').evaluate(node => (node as HTMLElement).inert)).toBe(false)
  await expect(frame.locator('#main')).toBeFocused()
})
